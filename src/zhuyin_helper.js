function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

const BOPOMOFO_SYL_RE = /(?:˙)?[ㄅ-ㄩ]+(?:[ˊˇˋ˙])?/g;

function renderVerticalZhuyinSyllable(rawSyl, variant = 'inline') {
  if (!rawSyl) return '';
  const hasLight = rawSyl.includes('˙');
  const toneMatch = rawSyl.match(/[ˊˇˋ]/);
  const tone = toneMatch ? toneMatch[0] : '';
  const syms = Array.from(rawSyl.replace(/[ˊˇˋ˙\s]/g, ''));
  if (!syms.length) return escapeHtml(rawSyl);

  const cls = [
    'zy-vbox',
    `zy-${variant}`,
    `zy-len-${syms.length}`,
    tone ? 'has-tone' : '',
    hasLight ? 'has-light' : '',
  ].filter(Boolean).join(' ');

  const lightHtml = hasLight ? '<span class="zy-light">˙</span>' : '';
  const symsHtml = syms.map((s) => `<span class="zy-s">${s}</span>`).join('');
  const toneHtml = tone ? `<span class="zy-tone">${tone}</span>` : '';

  return `<span class="${cls}" aria-label="${escapeHtml(rawSyl)}">${lightHtml}<span class="zy-body"><span class="zy-syms">${symsHtml}</span>${toneHtml}</span></span>`;
}

function renderVerticalZhuyin(text, variant = 'hero') {
  if (!text) return '';
  const safe = escapeHtml(text);
  return safe.replace(BOPOMOFO_SYL_RE, (m) => renderVerticalZhuyinSyllable(m, variant));
}

function renderCharWithZhuyin(ch, zy, rubyVariant = 'k2ruby') {
  if (!zy) return escapeHtml(ch);
  return `<span class="zy-char k2-char-pair"><span class="zy-han">${escapeHtml(ch)}</span><span class="zy-rt">${renderVerticalZhuyinSyllable(zy, rubyVariant)}</span></span>`;
}

function annotateZhuyin(text, enabled = true, excludeChars = '') {
  if (!text) return '';
  let out = escapeHtml(text);
  const placeholders = [];

  if (enabled) {
    const exSet = new Set(Array.from(excludeChars || '').filter((c) => /[\u4e00-\u9fff]/.test(c)));
    // Sort longest words first so multi-char phrases match before 2-char subwords
    const sorted = [...WORD_ZHUYIN_PAIRS].sort((a, b) => b[0].length - a[0].length);
    for (const [word, zyList] of sorted) {
      if (!out.includes(word)) continue;
      if (exSet.size > 0 && Array.from(word).some((ch) => exSet.has(ch))) continue;
      const wordHtml = Array.from(word)
        .map((ch, idx) => {
          const zy = zyList[idx];
          if (!zy) return ch;
          return `<span class="zy-char"><span class="zy-han">${ch}</span><span class="zy-rt">${renderVerticalZhuyinSyllable(zy, 'ruby')}</span></span>`;
        })
        .join('');
      const token = `\uE000${placeholders.length}\uE001`;
      placeholders.push(wordHtml);
      out = out.split(word).join(token);
    }
  }

  // Always render any explicit Bopomofo syllables in the text vertically too!
  out = out.replace(BOPOMOFO_SYL_RE, (m) => renderVerticalZhuyinSyllable(m, 'inline'));

  placeholders.forEach((html, i) => {
    out = out.split(`\uE000${i}\uE001`).join(html);
  });
  return out;
}

module.exports = { annotateZhuyin, renderVerticalZhuyin, renderVerticalZhuyinSyllable, renderCharWithZhuyin, escapeHtml };


